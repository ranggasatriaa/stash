<?php

namespace App\Stash\Transfer;

use Symfony\Component\Yaml\Yaml;

/**
 * One-way, Obsidian-compatible Markdown snapshot. Layout:
 *   Resources/{resource_id}.md, Projects/{project_id}.md,
 *   attachments/{file_id}.{ext}, Stash index.md
 * Front matter is produced by a real YAML serializer; Markdown text is
 * escaped. This is a downloadable snapshot, not a sync.
 */
final class ObsidianWriter
{
    /**
     * @param  array{projects: array<int, array<string, mixed>>, tags: array<int, array<string, mixed>>, resources: array<int, array<string, mixed>>, exported_at: string, counts: array{resources: int, projects: int, tags: int, attachments: int}, ...}  $document  export document from ExportDataBuilder
     * @return array<string, string> path => contents
     */
    public function notes(array $document): array
    {
        $projects = collect($document['projects'])->keyBy('id');
        $tags = collect($document['tags'])->keyBy('id');
        $byProject = [];
        $notes = [];

        foreach ($document['resources'] as $r) {
            $tagNames = array_values(array_filter(array_map(fn ($id) => $tags[$id]['name'] ?? null, $r['tag_ids'])));
            sort($tagNames, SORT_NATURAL | SORT_FLAG_CASE);
            $project = $r['project_id'] ? ($projects[$r['project_id']] ?? null) : null;

            $front = [
                'id' => $r['id'],
                'title' => $r['title'],
                'type' => $r['type'],
                'url' => $r['url'],
                'tags' => array_values(array_unique(array_map([self::class, 'obsidianTag'], $tagNames))),
                'stash_tags' => $tagNames,
                'project' => $project ? '[[Projects/'.$project['id'].'|'.self::wikiAlias($project['name']).']]' : null,
                'project_id' => $r['project_id'],
                'read_later' => (bool) $r['read_later'],
                'reading_status' => $r['reading_status'],
                'read_at' => $r['read_at'],
                'archived' => $r['archived_at'] !== null,
                'trashed' => $r['deleted_at'] !== null,
                'created' => $r['created_at'],
                'updated' => $r['updated_at'],
                'source' => 'stash',
            ];

            $body = '# '.self::escape($r['title'])."\n\n";
            if ($r['description']) {
                foreach (preg_split('/\R/u', (string) $r['description']) ?: [] as $line) {
                    $body .= '> '.self::escape($line)."\n";
                }
                $body .= "\n";
            }
            if ($r['url']) {
                $body .= '[Open source]('.self::linkTarget($r['url']).")\n\n";
            }
            foreach ($r['files'] as $file) {
                if ($file['path']) {
                    $body .= '!['.self::escape($r['title']).'](../'.$file['path'].")\n\n";
                }
            }
            if ($project) {
                $body .= 'Project: [['.'Projects/'.$project['id'].'|'.self::wikiAlias($project['name'])."]]\n\n";
            }

            $body .= "## Notes\n\n".(trim((string) $r['personal_notes']) !== '' ? rtrim((string) $r['personal_notes'])."\n\n" : "_No personal notes._\n\n");

            $summary = end($r['summaries']) ?: null;
            if ($summary && $summary['summary']) {
                $body .= "## AI summary\n\n";
                $body .= '> [!info] AI-generated summary · '.self::escape((string) $summary['model']).' · '.substr((string) $summary['created_at'], 0, 10)."\n";
                $body .= '> This text was generated by an AI model from '.self::escape(self::sourceLabel((string) $summary['source_kind'])).' and may contain errors.'."\n\n";
                $body .= self::escape((string) $summary['summary'])."\n\n";
                foreach ($summary['key_points'] ?? [] as $point) {
                    $body .= '- '.self::escape((string) $point)."\n";
                }
                $body .= "\n";
            }

            $notes['Resources/'.$r['id'].'.md'] = self::frontMatter($front).$body;
            if ($project) {
                $byProject[$project['id']][] = $r;
            }
        }

        foreach ($document['projects'] as $p) {
            $front = [
                'id' => $p['id'],
                'name' => $p['name'],
                'color' => $p['color'],
                'created' => $p['created_at'],
                'updated' => $p['updated_at'],
                'source' => 'stash',
            ];
            $body = '# '.self::escape($p['name'])."\n\n";
            if ($p['description']) {
                $body .= self::escape((string) $p['description'])."\n\n";
            }
            $body .= "## Resources\n\n";
            foreach ($byProject[$p['id']] ?? [] as $r) {
                $body .= '- ['.self::escape($r['title']).'](../Resources/'.$r['id'].".md)\n";
            }
            if (empty($byProject[$p['id']])) {
                $body .= "_No resources in this snapshot._\n";
            }
            $notes['Projects/'.$p['id'].'.md'] = self::frontMatter($front).$body;
        }

        $index = "# Stash export\n\nSnapshot created ".$document['exported_at'].". This is a one-way copy: edits here are not synced back to Stash.\n\n";
        $index .= '- Resources: '.count($document['resources'])."\n- Projects: ".count($document['projects'])."\n- Tags: ".count($document['tags'])."\n";
        $notes['Stash index.md'] = $index;

        return $notes;
    }

    /** @param array<string, mixed> $data */
    public static function frontMatter(array $data): string
    {
        $data = array_filter($data, fn ($value) => $value !== null);

        return "---\n".Yaml::dump($data, 2, 2, Yaml::DUMP_EMPTY_ARRAY_AS_SEQUENCE)."---\n\n";
    }

    /** Escape CommonMark-significant characters in inline text. */
    public static function escape(string $text): string
    {
        $text = str_replace(["\r", "\n"], ' ', $text);
        $escaped = preg_replace('/([\\\\`*_{}\[\]()<>#+!|~])/', '\\\\$1', $text) ?? $text;
        // Leading characters that would start a list or block.
        $escaped = preg_replace('/^(\s*)([-=]|\d+[.)])/', '$1\\\\$2', $escaped) ?? $escaped;

        return $escaped;
    }

    public static function linkTarget(string $url): string
    {
        return '<'.str_replace(['<', '>', ' ', "\n", "\r"], ['%3C', '%3E', '%20', '', ''], $url).'>';
    }

    public static function obsidianTag(string $name): string
    {
        // "/" would create nested Obsidian tags, so it is replaced as well.
        $tag = preg_replace('/[^\p{L}\p{N}_\-]+/u', '-', $name) ?? $name;
        $tag = trim($tag, '-');
        if ($tag === '' || preg_match('/^\d+$/', $tag)) {
            $tag = 'tag-'.$tag;
        }

        return $tag;
    }

    private static function wikiAlias(string $text): string
    {
        return str_replace(['[', ']', '|', "\n"], ['(', ')', '-', ' '], $text);
    }

    private static function sourceLabel(string $kind): string
    {
        return match ($kind) {
            'metadata' => 'page metadata only',
            'pasted' => 'pasted text',
            default => 'the extracted article text',
        };
    }
}
